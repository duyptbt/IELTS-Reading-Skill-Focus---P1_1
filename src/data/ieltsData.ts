export function checkAnswerCorrectness(question: QuestionItem, rawInput: string): boolean {
  if (!rawInput) return false;
  const cleaned = rawInput.trim().toLowerCase().replace(/[.,/#!$%^&*;:{}=\-_`~()]/g, '');

  if (question.type === 'true_false_not_given') {
    const norm = cleaned.toUpperCase();
    if (question.officialAnswer === 'TRUE') {
      return norm === 'TRUE' || norm === 'T';
    } else if (question.officialAnswer === 'FALSE') {
      return norm === 'FALSE' || norm === 'F';
    } else if (question.officialAnswer === 'NOT GIVEN') {
      return norm === 'NOT GIVEN' || norm === 'NOTGIVEN' || norm === 'NG';
    }
  }

  // Short answer or Flow chart
  const userTokens = cleaned.split(/\s+/).filter(Boolean).join(' ');
  for (const accepted of question.acceptedAnswers) {
    const accTokens = accepted
      .trim()
      .toLowerCase()
      .replace(/[.,/#!$%^&*;:{}=\-_`~()]/g, '')
      .split(/\s+/)
      .filter(Boolean)
      .join(' ');
    if (userTokens === accTokens) return true;
  }

  // Q1: road
  if (question.id === 1 && (userTokens === 'road' || userTokens === 'a road')) {
    return true;
  }

  // Q2: conference
  if (question.id === 2 && (userTokens === 'conference' || userTokens === 'a conference')) {
    return true;
  }

  // Q3: proposals
  if (question.id === 3 && (userTokens === 'proposals' || userTokens === 'proposal')) {
    return true;
  }

  // Q4: launch
  if (question.id === 4 && (userTokens === 'launch' || userTokens === 'an official launch' || userTokens === 'official launch')) {
    return true;
  }

  // Q5: exhibition
  if (question.id === 5 && (userTokens === 'exhibition' || userTokens === 'an exhibition')) {
    return true;
  }

  // Q10: six metres / 6 metres
  if (question.id === 10) {
    if (
      [
        '6 metres',
        'six metres',
        '6 meters',
        'six meters',
        '6m',
        '6 m',
        'six m',
        'six',
        '6',
        'six metres below',
        '6 metres below',
      ].includes(userTokens)
    ) {
      return true;
    }
  }

  // Q11: moss / pads of moss
  if (question.id === 11) {
    if (['moss', 'pads of moss', 'pad of moss', 'pads moss'].includes(userTokens)) {
      return true;
    }
  }

  // Q12: hull / hull shape / the hull shape
  if (question.id === 12) {
    if (['hull', 'the hull', 'hull shape', 'the hull shape', 'the hull shapes'].includes(userTokens)) {
      return true;
    }
  }

  // Q13: cost and time / time and cost
  if (question.id === 13) {
    if (
      [
        'cost and time',
        'time and cost',
        'cost time',
        'time cost',
        'cost, time',
        'time, cost',
        'cost & time',
        'time & cost',
      ].includes(userTokens)
    ) {
      return true;
    }
  }

  return false;
}

